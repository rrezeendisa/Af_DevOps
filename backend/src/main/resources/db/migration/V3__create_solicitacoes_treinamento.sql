CREATE TABLE solicitacoes_treinamento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(20) NOT NULL,
    solicitado_por VARCHAR(64) NOT NULL,
    versao_modelo VARCHAR(50),
    mensagem VARCHAR(1000),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_solicitacoes_treinamento_status_valido
        CHECK (status IN ('PENDENTE', 'CONCLUIDO', 'FALHOU'))
);

CREATE INDEX ix_solicitacoes_treinamento_status ON solicitacoes_treinamento (status);
