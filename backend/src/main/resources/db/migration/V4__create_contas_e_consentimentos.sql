CREATE TABLE contas_colaborador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_usuario VARCHAR(64) NOT NULL,
    senha_hash VARCHAR(60) NOT NULL,
    colaborador_id BIGINT NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_contas_colaborador UNIQUE (colaborador_id),
    CONSTRAINT fk_contas_colaborador FOREIGN KEY (colaborador_id)
        REFERENCES colaboradores (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX ux_contas_nome_usuario_lower ON contas_colaborador (lower(nome_usuario));

CREATE TABLE consentimentos_ia (
    colaborador_id BIGINT PRIMARY KEY REFERENCES colaboradores (id) ON DELETE CASCADE,
    autorizado BOOLEAN NOT NULL,
    decidido_em TIMESTAMP WITH TIME ZONE NOT NULL
);
